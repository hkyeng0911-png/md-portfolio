def classify(text, mc, cap=False):
    """2026-11-04 확정 기준
    - skip   : 반응 없음·정보 없음·지켜봐야 함 등 내용 없는 의견
    - other  : 객관식 '가격' 선택, 또는 가격 / 날씨·시기 / 물량·재고·사이즈 결품 / 진열·매장 사정 언급 (디자인 언급이 같이 있어도)
    - design : 그 외 전부 (디자인·핏·컬러·소재 평가, 잘 팔림·고객층·선호 등 상품 반응)
    cap=True(캡모자)도 같은 기준."""
    t = (text or '').strip()
    if len(t) < 3: return 'skip'
    tn = re.sub(r'\s+', '', t)
    ds = sum(1 for k in DESIGN + CAP_DESIGN if k.replace(' ', '') in tn)
    os_ = sum(1 for k in OTHER if k.replace(' ', '') in tn)
    if SKIP_RE.search(tn) and ds == 0 and os_ == 0: return 'skip'
    if mc == 'price' or os_ > 0: return 'other'
    return 'design'

def grades():
    """매장등급.xlsx 읽기. 엑셀이 열려 있어 잠긴 경우 임시 복사본 → 마지막 성공본(grades.json) 순으로 대체."""
    import json, shutil, tempfile
    cache = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'grades.json')
    src = GRADE_XLSX
    try:
        try: wb = openpyxl.load_workbook(src, read_only=True, data_only=True)
        except PermissionError:
            tmp = os.path.join(tempfile.gettempdir(), '_grade_copy.xlsx'); shutil.copyfile(src, tmp)
            wb = openpyxl.load_workbook(tmp, read_only=True, data_only=True)
        ws = wb.worksheets[0]
        g = {str(r[0]).strip(): str(r[2]).strip() for r in ws.iter_rows(values_only=True) if r[0] and r[2] and str(r[2]).strip() in ('A', 'B', 'C')}
        json.dump(g, open(cache, 'w', encoding='utf-8'), ensure_ascii=False); return g
    except Exception as e:
        if os.path.exists(cache): print('매장등급.xlsx 읽기 실패, 이전 등급 사용:', e); return json.load(open(cache, encoding='utf-8'))
        raise

# 등급표에 없는 매장·사용자 지정 변경분 (2026-11-03 지시)
GRADE_OVERRIDE = {}

def grade_map(stores):
    """매장등급.xlsx + 서브라인 매장은 A + 사용자 지정 변경분 → {매장명: 등급}"""
    G = grades()
    for st in stores:
        if st.get('group') == '서브라인 매장' and not G.get(st['name']): G[st['name']] = 'A'
    G.update(GRADE_OVERRIDE)
    return G

